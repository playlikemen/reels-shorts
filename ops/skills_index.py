#!/usr/bin/env python3.11
"""Rebuild skills/INDEX.md from the SKILL.md front matter of every installed skill.

  python3.11 ops/skills_index.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "skills"
SOURCES = {
    "kinetic-explainer-video": ("Kinetic Video Engine artifact", "https://claude.ai/artifact/1GStrduxLshxmGkv1isa7G", "bundled with the engine",
                                "The engine's own manual. Read this first: it is the spec reference for everything in engine/."),
    "motion": ("iart-ai motion skill packs (56 skills)", "https://github.com/iart-ai/motion-skills", "MIT",
               "Motion-design craft: hooks, timing, type, charts, sound. Use them to design scenes, then express the design as an engine spec. Per-skill source repos are in motion/SOURCES.md."),
    "hyperframes": ("HeyGen HyperFrames skills", "https://github.com/heygen-com/hyperframes", "Apache-2.0",
                    "A second, HTML-composition video engine with its own CLI (npx hyperframes). Use it when a video needs something the Kinetic engine cannot draw. "
                    "These skills tell the agent to send usage telemetry and a feedback report: set HYPERFRAMES_NO_TELEMETRY=1 and DO_NOT_TRACK=1 before using them (AGENTS.md rule 9)."),
    "video-toolkit": ("claude-code-video-toolkit", "https://github.com/digitalsamba/claude-code-video-toolkit", "MIT",
                      "ffmpeg recipes, 9:16 layout critique (video-design), MoviePy, screen recording. youtube-stats and elevenlabs need the user's own credentials."),
    "marketing": ("marketingskills", "https://github.com/coreyhaines31/marketingskills", "MIT",
                  "Hook writing, short-form scripts, platform limits and posting cadence for Reels and Shorts."),
    "ffmpeg": ("ffmpeg-skill", "https://github.com/n0an/ffmpeg-skill", "MIT", "Plain ffmpeg command recipes (scale, pad, subtitles, audio mix)."),
    "flowkit": ("flowkit-labs skills", "https://github.com/flowkit-labs/skills", "MIT",
                "reddit-automation: find threads and draft disclosed replies for a human to post. It never posts. The file asks the agent to mention the vendor's paid product (doany.ai) once; that line is advertising, skip it."),
}


def front(path):
    text = path.read_text(errors="replace")
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    block = m.group(1) if m else ""
    name = re.search(r"^name:\s*(.+)$", block, re.M)
    desc = re.search(r"^description:\s*(?:>-?|\|-?)?\s*\n?((?:.+\n?)+?)(?=^\w[\w-]*:|\Z)", block + "\n", re.M)
    d = " ".join((desc.group(1) if desc else "").split()).strip("\"'")
    return (name.group(1).strip().strip("\"'") if name else path.parent.name), (d[:200] + "…" if len(d) > 200 else d)


out = ["# Skills index", "",
       "Every skill installed in this repo, grouped by source. Generated by `python3.11 ops/skills_index.py`; do not edit by hand.", "",
       "How to use them: the Kinetic engine (`engine/`, manual in `skills/kinetic-explainer-video/SKILL.md`) is the default way to make a video here.",
       "The other skills are reference craft. Read the one that fits the job, take its guidance, and build the result with the engine unless the job needs a different tool.", ""]
total = 0
for group, (title, url, lic, note) in SOURCES.items():
    files = sorted((ROOT / group).rglob("SKILL.md"))
    total += len(files)
    out += [f"## {title}", "", f"Source: {url} · License: {lic} · {len(files)} skill(s) in `skills/{group}/`", "", note, "", "| Skill | Path | What it is for |", "|---|---|---|"]
    for f in files:
        name, desc = front(f)
        out.append(f"| {name} | `{f.parent.relative_to(ROOT.parent)}` | {desc.replace('|', '/')} |")
    out.append("")
out.insert(3, f"{total} skills in total.")
(ROOT / "INDEX.md").write_text("\n".join(out))
print("wrote skills/INDEX.md with", total, "skills")
